# compute TPSA and LogP for free SMILES and for ORCA complexed structures
def compute_table(smiles_dict, loader):
    rows = []
    for name, smi in smiles_dict.items():
        # compute free-state descriptors from SMILES so we have baseline properties
        m_free = Chem.MolFromSmiles(smi)
        tpsa_free = Descriptors.TPSA(m_free) if m_free else None
        logp_free = Descriptors.MolLogP(m_free) if m_free else None

        # load complexed structure from ORCA output using loader so we can compare changes
        fname = f"{name.lower()}_mg_singlepoint.out"
        m_complex = loader(fname, smi)
        if m_complex is None:
            tpsa_c = None; logp_c = None
        else:
            # compute descriptors on the complexed (3D) structure
            tpsa_c = Descriptors.TPSA(m_complex); logp_c = Descriptors.MolLogP(m_complex)

        # record values and deltas (complexed - free) when available
        rows.append({
            "Molecule": name,
            "TPSA_Free": tpsa_free,
            "LogP_Free": logp_free,
            "TPSA_Complexed": tpsa_c,
            "LogP_Complexed": logp_c,
            "ΔTPSA": (tpsa_c - tpsa_free) if (tpsa_c is not None and tpsa_free is not None) else None,
            "ΔLogP": (logp_c - logp_free) if (logp_c is not None and logp_free is not None) else None
        })
    df = pd.DataFrame(rows)

    # label rows "Likely permeable" or "Unlikely" using TPSA and LogP thresholds for free state
    df["BBB_Prediction_Free"] = df.apply(
        lambda r: ("Likely permeable"
                   if (r["TPSA_Free"] is not None and r["TPSA_Free"] <= BBB_TPSA_THRESHOLD and r["LogP_Free"] >= BBB_LOGP_THRESHOLD)
                   else ("Unlikely" if r["TPSA_Free"] is not None else None)),
        axis=1
    )

    # label rows "Likely permeable" or "Unlikely" using TPSA and LogP thresholds for complexed state
    df["BBB_Prediction_Complexed"] = df.apply(
        lambda r: ("Likely permeable"
                   if (r["TPSA_Complexed"] is not None and r["TPSA_Complexed"] <= BBB_TPSA_THRESHOLD and r["LogP_Complexed"] >= BBB_LOGP_THRESHOLD)
                   else ("Unlikely" if r["TPSA_Complexed"] is not None else None)),
        axis = 1
    )

    # compute a simple confidence score for free-state BBB prediction (0-1 scaled)
    df["BBB_Confidence"] = df.apply(
        lambda r: None if r["TPSA_Free"] is None or r["LogP_Free"] is None
        else round(((max(0, BBB_TPSA_THRESHOLD - r['TPSA_Free'])/BBB_TPSA_THRESHOLD) +
                    (max(0, r['LogP_Free'] - BBB_LOGP_THRESHOLD)/3))/2, 3),
        axis = 1
    )

    return df

