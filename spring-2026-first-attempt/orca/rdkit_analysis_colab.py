def check_atom_count(smiles, out_file):
    # count atoms in SMILES
    mol = Chem.AddHs(Chem.MolFromSmiles(smiles))
    n_smiles = mol.GetNumAtoms()

    # count atoms in ORCA file
    atoms = []
    rec = False
    with open(out_file, "r") as fh:
        for line in fh:
            if "CARTESIAN COORDINATES (ANGSTROEM)" in line:
                rec = True
                next(fh, None)
                continue
            if rec:
                if line.strip() == "":
                    break
                parts = line.split()
                if len(parts) >= 4:
                    atoms.append(parts[0])
    return n_smiles, len(atoms)

