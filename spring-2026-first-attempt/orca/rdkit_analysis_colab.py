def check_smiles_match(smiles, mol):
    if mol is None:
        return False, None, None
    sm_free = Chem.MolToSmiles(Chem.MolFromSmiles(smiles), canonical=True)
    sm_complex = Chem.MolToSmiles(Chem.RemoveHs(mol), canonical=True)
    return sm_free == sm_complex, sm_free, sm_complex

